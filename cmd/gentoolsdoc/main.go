// Command gentoolsdoc regenerates docs/AGENT_TOOLS.md from the agentguide registry.
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"releasecontrol/internal/agentguide"
)

func main() {
	if err := os.WriteFile("docs/AGENT_TOOLS.md", []byte(render()), 0644); err != nil {
		panic(err)
	}
}

func render() string {
	var b strings.Builder
	b.WriteString("<!-- Generated by `go run ./cmd/gentoolsdoc`; do not edit by hand. -->\n# Agent tool reference\n\nUse `get_tool_guide {}` for the compact index and `get_tool_guide {\"name\":\"…\"}` for a full entry. This guide describes interfaces; it grants no authority.\n\n")
	areas := map[string][]agentguide.ToolEntry{}
	for _, e := range agentguide.Registry() {
		areas[e.Area] = append(areas[e.Area], e)
	}
	keys := make([]string, 0, len(areas))
	for k := range areas {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, area := range keys {
		b.WriteString("## " + strings.ReplaceAll(area, "_", " ") + "\n\n")
		for _, e := range areas[area] {
			b.WriteString("### `" + e.Name + "` — " + e.Kind + "\n\n")
			b.WriteString(e.Purpose + "\n\n**When:** " + e.When + "\n\n**Inputs:**\n\n")
			for _, f := range e.Inputs {
				b.WriteString("- `" + f.Name + "` (" + f.Type + ", ")
				if f.Required {
					b.WriteString("required")
				} else {
					b.WriteString("optional")
				}
				b.WriteString("): " + f.Meaning + "\n")
			}
			b.WriteString("\n**Output:** " + e.Output + "\n\n**Errors:**\n\n")
			for _, x := range e.Errors {
				b.WriteString("- `" + x.Code + "`: " + x.Meaning + "\n")
			}
			b.WriteString("\n**Example:** `" + strings.ReplaceAll(e.Example, "`", "\\`") + "`\n\n**Related:** `" + strings.Join(e.Related, "`, `") + "`\n\n**Authority:** " + e.Authority + "\n\n")
		}
	}
	b.WriteString("## Pending documentation\n\nThe registry tracks remaining interfaces explicitly; later stages must reduce this list to zero.\n\n")
	for _, p := range agentguide.PendingDocumentation() {
		b.WriteString("- `" + p + "`\n")
	}
	return b.String()
}

