func TestCodeIndexGolden(t *testing.T) {
	doc, err := Build(context.Background(), "fixture", "testdata/checkout", time.Unix(100, 0), Options{})
	if err != nil {
		t.Fatal(err)
	}
	var output strings.Builder
	for _, file := range doc.Files {
		fmt.Fprintf(&output, "%s | %s | %d\n", file.Path, file.Language, file.Lines)
		for _, symbol := range file.Symbols {
			fmt.Fprintf(&output, "  %s %s %q %d %q\n", symbol.Kind, symbol.Name, symbol.Receiver, symbol.Line, symbol.Doc)
		}
		for _, route := range file.Routes {
			fmt.Fprintf(&output, "  route %s %s %d\n", route.Method, route.Path, route.Line)
		}
		for _, dep := range file.Dependencies {
			fmt.Fprintf(&output, "  dependency %s %s %q\n", dep.Kind, dep.Name, dep.Version)
		}
		for _, entry := range file.Entrypoints {
			fmt.Fprintf(&output, "  entry %s %s\n", entry.Kind, entry.Name)
		}
		if file.Doc != "" {
			fmt.Fprintf(&output, "  doc %q\n", file.Doc)
		}
	}
	want, err := os.ReadFile("testdata/index.golden")
	if err != nil || string(want) != output.String() {
		t.Fatalf("golden mismatch (%v):\n%s", err, output.String())
	}
	second, err := Build(context.Background(), "fixture", "testdata/checkout", time.Unix(200, 0), Options{})
	if err != nil {
		t.Fatal(err)
	}
	firstDigest, _ := doc.Digest()
	secondDigest, _ := second.Digest()
	if firstDigest != secondDigest || doc.IndexedAt.Equal(second.IndexedAt) {
		t.Fatal("observation timestamp affected the digest")
	}
}

func indexFixtureFile(t *testing.T, root, name, content string) {
	t.Helper()
	target := filepath.Join(root, name)
	if err := os.MkdirAll(filepath.Dir(target), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(target, []byte(content), 0600); err != nil {
		t.Fatal(err)
	}
}

func TestCodeIndexFilters(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("Git required for ignore test")
	}
	root := t.TempDir()
	git := func(args ...string) {
		command := exec.Command("git", append([]string{"-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", "-c", "commit.gpgsign=false", "-c", "core.hooksPath=" + os.DevNull, "-C", root}, args...)...)
		if out, err := command.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v: %s", args, err, out)
		}
	}
	git("init", "-b", "main")
	indexFixtureFile(t, root, ".gitignore", "ignored.py\n")
	git("add", ".gitignore")
	git("commit", "-m", "fixture")
	token := "ghp_" + strings.Repeat("A", 36)
	for name, content := range map[string]string{
		"ignored.py": "class NotIndexed: pass", ".env.example": "VALUE=visible", "private.pem": "plain text", "nested/credentials.json": "{}",
		"secret.py": "value = '" + token + "'", "docs/secret.md": "Public text followed by " + token,
		"docs/inline.md": "Use `API_TOKEN=OpaqueFixture987` for testing.\n",
		"docs/crlf.md":   "API_TOKEN=OpaqueFixture987\r\nMore text\r\n",
		"binary.txt":     "hi\x00bye", "large.txt": strings.Repeat("x", domain.CodeFileBytes+1), "tiny.min.js": "export const x = 1;",
		"compact.js": strings.Repeat("window.fn();", 500), "generated.go": "// Code generated by fixture; DO NOT EDIT.\npackage test", "yarn.lock": token,
		".mcp.json": "{}", "keep.py": "class Keep: pass",
	} {
		indexFixtureFile(t, root, name, content)
	}
	doc, err := Build(context.Background(), "fixture", root, time.Now(), Options{IncludeUntracked: true})
	if err != nil {
		t.Fatal(err)
	}
	if doc.Branch != "main" || len(doc.Commit) != 40 || len(doc.Files) != 3 || doc.Files[0].Path != ".gitignore" || doc.Files[1].Path != "keep.py" || doc.Files[2].Path != "yarn.lock" || doc.Files[2].Lines != 0 {
		t.Fatalf("unexpected filtered index: %+v", doc)
	}
	wire, _ := json.Marshal(doc)
	if strings.Contains(string(wire), token) {
		t.Fatal("token escaped filter")
	}
}

func TestCodeIndexDockerDropsArguments(t *testing.T) {
	root := t.TempDir()
	indexFixtureFile(t, root, "Dockerfile", "CMD [\"serve\",\"--password\",\"OpaqueFixture987\"]\nENTRYPOINT /entry --password OpaqueFixture987\n")
	doc, err := Build(context.Background(), "fixture", root, time.Now(), Options{})
	want := []domain.CodeEntry{{Kind: "docker_cmd", Name: "serve"}, {Kind: "docker_entrypoint", Name: "/entry"}}
	if err != nil || len(doc.Files) != 1 || !slices.Equal(doc.Files[0].Entrypoints, want) {
		t.Fatalf("Docker entry points: %+v, %v", doc.Files, err)
	}
}

func TestCodeIndexLineEndingParity(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("Git required for checkout parity test")
	}
	root := t.TempDir()
	git := func(args ...string) {
		t.Helper()
		command := exec.Command("git", append([]string{"-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", "-c", "commit.gpgsign=false", "-c", "core.hooksPath=" + os.DevNull, "-C", root}, args...)...)
		if out, err := command.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v: %s", args, err, out)
		}
	}
	git("init", "-b", "main")
	git("config", "core.autocrlf", "false")
	indexFixtureFile(t, root, ".gitattributes", "* text\n")
	indexFixtureFile(t, root, "README.md", "# Architecture\nSecond line\n")
	indexFixtureFile(t, root, "another.txt", strings.Repeat("x\n", domain.CodeFileBytes/2))
	indexFixtureFile(t, root, "cmd/main.go", "package main\n\n// Serve launches the service.\nfunc Serve() {}\n")
	indexFixtureFile(t, root, "yarn.lock", "lock metadata only\n")
	git("add", ".")
	git("commit", "-m", "fixture")
	build := func() domain.CodeIndex {
		t.Helper()
		doc, err := Build(context.Background(), "fixture", root, time.Now(), Options{})
		if err != nil || len(doc.Files) != 5 {
			t.Fatalf("expected five indexed files, got %d, %v", len(doc.Files), err)
		}
		return doc
	}
	lf := build()
	git("config", "core.autocrlf", "true")
	for _, file := range lf.Files {
		if err := os.Remove(filepath.Join(root, file.Path)); err != nil {
			t.Fatal(err)
		}
	}
	git("checkout-index", "--all", "--force")
	raw, err := os.ReadFile(filepath.Join(root, "README.md"))
	if err != nil || !strings.Contains(string(raw), "\r\n") {
		t.Fatalf("checkout did not convert to CRLF: %q, %v", raw, err)
	}
	crlf := build()
	first, errLF := lf.Digest()
	second, errCRLF := crlf.Digest()
	if errLF != nil || errCRLF != nil || first != second {
		t.Fatalf("LF/CRLF digests: %s (%v) vs %s (%v)", first, errLF, second, errCRLF)
	}
}

func TestCodeIndexTruncation(t *testing.T) {
	for _, tc := range []struct{ name, character, flag string }{{"docs", "x", "docs_bytes"}, {"wire", "<", "bytes"}} {
		t.Run(tc.name, func(t *testing.T) {
			root := t.TempDir()
			for n := 0; n < 34; n++ {
				indexFixtureFile(t, root, fmt.Sprintf("docs/%02d.md", n), strings.Repeat(tc.character, domain.CodeDocBytes+1))
			}
			doc, err := Build(context.Background(), "fixture", root, time.Now(), Options{})
			if err != nil || !slices.Contains(doc.Truncated, tc.flag) || !slices.Contains(doc.Truncated, "doc_bytes") {
				t.Fatalf("truncation = %v, error = %v", doc.Truncated, err)
			}
		})
	}
}
